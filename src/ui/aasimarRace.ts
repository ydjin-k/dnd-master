/**
 * Одна из пяти рас пачки B — «Аасимар». Наша собственная, не SRD.
 *
 * ГДЕ ОНА ЖИВЁТ И ПОЧЕМУ ИМЕННО ЗДЕСЬ. Разобрано один раз и общо для всех наших
 * рас — `docs/design/own-races-how-to.md` и шапка `abyssElfRace.ts`. Коротко: в
 * `src-tauri/rules/rules.json` лежит ровно SRD 5.1, подвал вкладки «Правила»
 * обещает SRD за всё, что пришло оттуда, и раса, положенная в тот файл, молча
 * получила бы чужую подпись. Поэтому наша раса — отдельный модуль, а факт «это
 * наше» объявлен ровно в одном месте: `OWN_RULE_TOPICS` (`ownRuleTopics.ts`).
 *
 * ОТКУДА ВЗЯТО ИМЯ. Решение владельца 27.09.2026: имена десяти новых рас берутся
 * из его файлов («их брать можно, это информация в свободном доступе»), а
 * содержание пишется своё. Имя прогнано по сторожу
 * `own_creatures_never_use_product_identity_names` (`combat.rs`) — ни под одну
 * из 36 основ `FORBIDDEN_STEMS` и ни под одно из 9 слов `FORBIDDEN_WORDS` оно не
 * попадает.
 *
 * ВИДОВ В МЕХАНИКЕ У ЭТОЙ РАСЫ НЕТ — решение владельца 07.10.2026, и оно здесь
 * главное. У чужой расы той же ниши три вида, и каждый меняет и бонус
 * характеристик, и особенность уровня. У нас **одна раса**: одна строка в
 * `OWN_RULE_TOPICS`, один модуль, один набор особенностей и один набор бонусов.
 * Три дороги аасимара (заступник, мститель, погасший) живут ТОЛЬКО в прозе и в
 * строках таблицы к8 — ни бонусов, ни особенностей они не меняют, и механизм
 * выбора варианта расы (пункт 2а карточки) этой расе не нужен вовсе: он заводится
 * для Дженази.
 *
 * ЧТО ВЗЯТО ИЗ SRD, А ЧТО НАШЕ. Границу видно построчно:
 * - из открытого бестиария (`src-tauri/bestiary/bestiary.json`, подпись
 *   CC BY 4.0) взято два факта. Первый — **язык Небесный**: он назван в
 *   открытых стат-блоках `unicorn` и `guardian-naga`, а `pegasus` его понимает,
 *   и наша раса небесного следа берёт язык оттуда. Второй — **сопротивление
 *   к лучистому урону**: оно стоит в открытых стат-блоках `deva`, `planetar`,
 *   `solar` и `couatl`, и наш «Небесный след» повторяет его, а не заводит
 *   вторую формулировку того же правила;
 * - из открытого SRD (`rules.json`) взято одно слово — **«стабилизировать»**:
 *   состояние умирающего существа там уже описано («Первая помощь»,
 *   спасброски от смерти), и «Ладони света» ссылаются на него, а не вводят
 *   своё понятие стабильности;
 * - из открытого SRD взяты и **радиусы света**: «яркий свет в пределах 20 футов
 *   и тусклый свет в пределах ещё 20 футов» — это факел из снаряжения
 *   `rules.json`. Числа чужого вида (10 и 10) здесь не стоят сознательно;
 * - наше: бонусы характеристик, скорость, размер, навык, который раса даёт
 *   сама, три особенности ниже («Небесный след» как правило расы, «Свет под
 *   кожей», «Ладони света»), вся проза, все четыре таблицы, возраст,
 *   мировоззрение, рост и три дороги.
 *
 * Играбельный аасимар из чужой книги как пакет здесь не воспроизводится.
 * Оттуда не взято НИ ОДНОГО числа и ни одной черты: у чужой расы Харизма +2 и
 * ещё +1 по виду, тёмное зрение на 60 футов, сопротивление сразу двум видам
 * урона, исцеление на величину уровня действием, заговор света и превращение с
 * третьего уровня — у всех трёх видов своё, с крыльями, светом из глаз и
 * спасброском от испуга. Здесь бонус стоит НЕ на Харизме двойкой, тёмного
 * зрения нет вовсе, сопротивление одно, хитов раса не восстанавливает,
 * заклинаний не даёт ни одного, а свечение кожи ничего не поджигает и ни на
 * чей уровень не смотрит.
 *
 * ПОЧЕМУ БОНУС НЕ НА ХАРИЗМЕ. Все три чужих вида стоят на Харизме +2, и
 * расхождение с пакетом тут проверяемо числом: у нас Мудрость +2 и Харизма +1.
 * По нише это и вернее — аасимара ведут сны и видения наставника, а свет он
 * несёт, а не продаёт. Пара заодно разошлась с нашими Сатиром и Чейнджлингом
 * (у обоих Харизма +2) и с нашим Фирболгом (Мудрость +2 и Телосложение +1).
 *
 * ЧЕГО У ЭТОЙ РАСЫ НЕТ И ПОЧЕМУ. Заклинаний она не даёт ни одного, и заговор
 * света — первое, чего пришлось не брать: раздатчики заговоров и расовых ячеек
 * сегодня умеют ровно одну расу (Эльфа бездны), обобщать их — отдельная
 * карточка, а дописать ветку в `abyssElfRace.ts` значило бы сделать файл Эльфа
 * бездны владельцем чужих фактов. Поэтому свет у нас — особенность, а не
 * заклинание. Тёмного зрения у неё нет: у открытых небожителей единого числа
 * для него не найти (у `deva` — 120 футов, у `unicorn` — 60, у `planetar` и
 * `solar` вместо него истинное зрение, у `pegasus` чувств нет вовсе), а
 * выдумать своё значило бы выдумать число. Прибавки к хитам у неё нет.
 * Скорость она объявляет базой (`RACE_SPEED_FEET`), а не слоем к
 * `effectiveStats.ts`.
 */

