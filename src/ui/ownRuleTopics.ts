import type { RuleTopic } from "../state/types";
import { ABYSS_ELF_TOPIC } from "./abyssElfRace";

/**
 * Наши собственные темы справочника — те, что приложение показывает во вкладке
 * «Правила» рядом с SRD, но под своей подписью.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ СПИСОК. Просьба владельца 27.09.2026: наша раса стоит в
 * разделе «Расы» рядом с Эльфом и Гномом, наш класс — в «Классах» рядом с
 * Бардом, отдельных разделов «Наши расы» и «Наши классы» нет. Значит по
 * категории наше от SRD не отличить: у Эльфа бездны категория `races` ровно
 * та же, что у девяти рас справочника. Различать по категории значило бы либо
 * подписать SRD как наше, либо наше как SRD — и то и другое врёт игроку об
 * источнике.
 *
 * Поэтому факт «это наше» живёт здесь и только здесь: тема наша тогда и только
 * тогда, когда она в этом списке (`isOwnRuleTopic`). Подвал страницы правил
 * спрашивает именно его, а не категорию.
 *
 * ПОЧЕМУ НЕ В `rules.json`. В `src-tauri/rules/rules.json` лежит ровно SRD 5.1,
 * и подвал обещает SRD за всё, что пришло оттуда. Тема, положенная в тот файл,
 * получила бы эту подпись молча. Тот же довод уже отработан четырежды:
 * `wildMagicSurges.ts`, `abyssElfRace.ts`, `optionalRules.ts`, бестиарий
 * (`bestiary/own-creatures.json`). Граница «всё, что из rules.json, — SRD»
 * проверяема ровно до тех пор, пока в него ничего не подмешано.
 *
 * КАК ДОБАВИТЬ СЛЕДУЮЩУЮ РАСУ ИЛИ КЛАСС. Одной строкой в этот список: тема
 * несёт свою категорию сама, поэтому ни новых разделов в `CATEGORY_LABEL`, ни
 * правок в `RulesPage` не нужно. Раса с категорией `races` заодно встаёт в
 * мастер создания — её подхватит `playableRaces` ниже.
 *
 * Жилец сегодня один — это нормально: смысл списка в том, чтобы второй жилец
 * не потребовал ни строки кода.
 */
export const OWN_RULE_TOPICS: readonly RuleTopic[] = [ABYSS_ELF_TOPIC];

/** Категория, по которой раса попадает в мастер создания, — та же, что у SRD-рас. */
const RACES_CATEGORY = "races";

/**
 * Общая статья «Расовые особенности» из справочника — не раса, играть ею
 * нельзя, поэтому из списка выбора она выброшена.
 */
const RACE_TRAITS_TOPIC_ID = "races-traits";

/**
 * Наша ли это тема? Единственный способ ответить: по принадлежности списку, не
 * по категории и не по пустому `sourceUrl`.
 */
export function isOwnRuleTopic(topic: RuleTopic | null | undefined): boolean {
  if (!topic) return false;
  return OWN_RULE_TOPICS.some((own) => own.id === topic.id);
}

/**
 * Полный список рас для мастера создания: девять из справочника SRD плюс наши.
 * Единственный владелец факта «кем можно играть».
 *
 * Живёт здесь, а не в `abyssElfRace.ts`, чтобы список наших тем был РОВНО
 * один: раньше эта функция приписывала `ABYSS_ELF_TOPIC` руками и тем знала то
 * же, что `OWN_RULE_TOPICS`, — два владельца одного факта. Теперь наши расы
 * отбираются из общего списка по категории, и следующая раса доезжает до
 * мастера без правок здесь.
 *
 * Обратного импорта (`abyssElfRace.ts` → этот модуль) быть не должно: круг
 * импортов; поэтому функция и переехала, а не осталась на месте.
 */
export function playableRaces(topics: RuleTopic[]): RuleTopic[] {
  const srdRaces = topics.filter(
    (t) => t.category === RACES_CATEGORY && t.id !== RACE_TRAITS_TOPIC_ID,
  );
  const ownRaces = OWN_RULE_TOPICS.filter((t) => t.category === RACES_CATEGORY);
  return [...srdRaces, ...ownRaces];
}
