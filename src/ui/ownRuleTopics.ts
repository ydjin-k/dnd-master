import type { RuleBlock, RuleTopic } from "../state/types";
import { ABYSS_ELF_TOPIC } from "./abyssElfRace";
import { GOBLIN_TOPIC } from "./goblinRace";
import { SATYR_TOPIC } from "./satyrRace";
import { CHANGELING_TOPIC } from "./changelingRace";
import { GOLIATH_TOPIC } from "./goliathRace";
import { SERPENT_TOPIC } from "./serpentRace";
import { TABAXI_TOPIC } from "./tabaxiRace";

/**
 * Наши собственные темы справочника — те, что приложение показывает во вкладке
 * «Правила» рядом с SRD, но под своей подписью.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ СПИСОК. Просьба владельца 27.09.2026: наша раса стоит в
 * разделе «Расы» рядом с Эльфом и Гномом, наш класс — в «Классах» рядом с
 * Бардом, отдельных разделов «Наши расы» и «Наши классы» нет. Значит по
 * категории наше от SRD не отличить: у Эльфа бездны категория `races` ровно
 * та же, что у девяти рас справочника. Различать по категории значило бы либо
 * подписать SRD как наше, либо наше как SRD — и то и другое врёт игроку об
 * источнике.
 *
 * Поэтому факт «это наше» живёт здесь и только здесь: тема наша тогда и только
 * тогда, когда она в этом списке (`isOwnRuleTopic`). Подвал страницы правил
 * спрашивает именно его, а не категорию.
 *
 * ПОЧЕМУ НЕ В `rules.json`. В `src-tauri/rules/rules.json` лежит ровно SRD 5.1,
 * и подвал обещает SRD за всё, что пришло оттуда. Тема, положенная в тот файл,
 * получила бы эту подпись молча. Тот же довод уже отработан четырежды:
 * `wildMagicSurges.ts`, `abyssElfRace.ts`, `optionalRules.ts`, бестиарий
 * (`bestiary/own-creatures.json`). Граница «всё, что из rules.json, — SRD»
 * проверяема ровно до тех пор, пока в него ничего не подмешано.
 *
 * КАК ДОБАВИТЬ СЛЕДУЮЩУЮ РАСУ ИЛИ КЛАСС. Одной строкой в этот список: тема
 * несёт свою категорию сама, поэтому ни новых разделов в `CATEGORY_LABEL`, ни
 * правок в `RulesPage` не нужно. Раса с категорией `races` заодно встаёт в
 * мастер создания — её подхватит `playableRaces` ниже.
 *
 * Обещание сдержалось: пачка `characters-races-pack-a` добавила к Эльфу бездны
 * пять рас, и каждая стоила ровно одной строки в списке ниже — ни новых
 * разделов в `CATEGORY_LABEL`, ни правок в `RulesPage`, ни второго места,
 * знающего про происхождение.
 *
 * ПОРЯДОК В СПИСКЕ значащий, и менять его без причины нельзя: `playableRaces`
 * отдаёт наши расы в этом же порядке после девяти SRD-рас, так что Эльф бездны
 * остаётся десятым в мастере создания, а новые расы встают за ним.
 */
export const OWN_RULE_TOPICS: readonly RuleTopic[] = [
  ABYSS_ELF_TOPIC,
  GOBLIN_TOPIC,
  SATYR_TOPIC,
  SERPENT_TOPIC,
  CHANGELING_TOPIC,
  GOLIATH_TOPIC,
  TABAXI_TOPIC,
];


/**
 * Заголовок раздела механики. Одинаков у всех пятнадцати рас: девять статей
 * SRD начинают им статью сразу после названия («Особенности дварфов»,
 * «Особенности эльфов»), наши шесть ставят его третьим, после двух разделов
 * культуры. Проверено по `rules.json` — исключений нет ни одного.
 */
const MECHANICS_HEADING_PREFIX = "Особенности";

/**
 * Заголовок раздела происхождения — первый из тех, что в мастере не нужны.
 * Есть только у наших рас («Почему ты ушёл из племени» и соседи); у SRD
 * такого раздела нет, и срез там просто доходит до конца статьи.
 */
const ROLEPLAY_HEADING_PREFIX = "Почему ты ";

/**
 * Что мастер создания показывает, когда расу выбрали.
 *
 * ЗАЧЕМ СРЕЗ. Просьба владельца 07.10.2026, после живой установки: «ты
 * добавил все элементы новой расы в мастер создания персонажа, там это не
 * нужно». И он прав: мастер — это ВЫБОР, а чтение — вкладка «Правила». У
 * наших рас статья выросла до 27–29 блоков с четырьмя таблицами бросков, и
 * выбирающий расу человек получал в лицо таблицу отыгрыша вместо чисел.
 *
 * ЭТОТ ПРИЁМ В ПРИЛОЖЕНИИ УЖЕ ЕСТЬ. Шаг «Класс» устроен ровно так же —
 * показывает шапку класса, а не все фичи по уровням (`CharacterWizard.tsx`,
 * срез `classIntroBlocks`). Расы просто догнали классы.
 *
 * ПРАВИЛО ОДНО НА ВСЕ ПЯТНАДЦАТЬ РАС — второе решение владельца того же дня:
 * «хочется, чтобы писалось везде одинаково». Поэтому срез НЕ спрашивает,
 * наша это раса или SRD: он идёт от раздела механики до раздела
 * происхождения, и разницу создаёт сама статья, а не исключение в коде.
 * У SRD-рас раздела происхождения нет, и срез доходит до конца — вместе с
 * подрасой («Холмовой дварф», «Высший эльф»), чьи бонусы мастер и выдаёт.
 *
 * ЕСЛИ ФОРМА СЛОМАЕТСЯ, показывается статья целиком: пустой шаг «Раса» —
 * отказ приложения, а лишний текст — всего лишь некрасиво.
 */
export function raceWizardBlocks(topic: RuleTopic): readonly RuleBlock[] {
  const isHeading = (block: RuleBlock, prefix: string) =>
    block.type === "heading" && block.level === 2 && block.text.startsWith(prefix);

  const start = topic.blocks.findIndex((block) => isHeading(block, MECHANICS_HEADING_PREFIX));
  if (start === -1) return topic.blocks;

  const end = topic.blocks.findIndex(
    (block, index) => index > start && isHeading(block, ROLEPLAY_HEADING_PREFIX),
  );
  return topic.blocks.slice(start, end === -1 ? topic.blocks.length : end);
}

/** Категория, по которой раса попадает в мастер создания, — та же, что у SRD-рас. */
const RACES_CATEGORY = "races";

/**
 * Общая статья «Расовые особенности» из справочника — не раса, играть ею
 * нельзя, поэтому из списка выбора она выброшена.
 */
const RACE_TRAITS_TOPIC_ID = "races-traits";

/**
 * Наша ли это тема? Единственный способ ответить: по принадлежности списку, не
 * по категории и не по пустому `sourceUrl`.
 */
export function isOwnRuleTopic(topic: RuleTopic | null | undefined): boolean {
  if (!topic) return false;
  return OWN_RULE_TOPICS.some((own) => own.id === topic.id);
}

/**
 * Полный список рас для мастера создания: девять из справочника SRD плюс наши.
 * Единственный владелец факта «кем можно играть».
 *
 * Живёт здесь, а не в `abyssElfRace.ts`, чтобы список наших тем был РОВНО
 * один: раньше эта функция приписывала `ABYSS_ELF_TOPIC` руками и тем знала то
 * же, что `OWN_RULE_TOPICS`, — два владельца одного факта. Теперь наши расы
 * отбираются из общего списка по категории, и следующая раса доезжает до
 * мастера без правок здесь.
 *
 * Обратного импорта (`abyssElfRace.ts` → этот модуль) быть не должно: круг
 * импортов; поэтому функция и переехала, а не осталась на месте.
 */
export function playableRaces(topics: RuleTopic[]): RuleTopic[] {
  const srdRaces = topics.filter(
    (t) => t.category === RACES_CATEGORY && t.id !== RACE_TRAITS_TOPIC_ID,
  );
  const ownRaces = OWN_RULE_TOPICS.filter((t) => t.category === RACES_CATEGORY);
  return [...srdRaces, ...ownRaces];
}
