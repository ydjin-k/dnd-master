/**
 * Одиннадцатая раса приложения — «Гоблин». Наша собственная, не SRD.
 *
 * ГДЕ ОНА ЖИВЁТ И ПОЧЕМУ ИМЕННО ЗДЕСЬ. Разобрано один раз и общо для всех наших
 * рас — `docs/design/own-races-how-to.md` и шапка `abyssElfRace.ts`. Коротко: в
 * `src-tauri/rules/rules.json` лежит ровно SRD 5.1, подвал вкладки «Правила»
 * обещает SRD за всё, что пришло оттуда, и раса, положенная в тот файл, молча
 * получила бы чужую подпись. Поэтому наша раса — отдельный модуль, а факт «это
 * наше» объявлен ровно в одном месте: `OWN_RULE_TOPICS` (`ownRuleTopics.ts`).
 *
 * ОТКУДА ВЗЯТО ИМЯ. Решение владельца 27.09.2026: имена десяти новых рас берутся
 * из его файлов («их брать можно, это информация в свободном доступе»), а
 * содержание пишется своё. Имя прогнано по сторожу
 * `own_creatures_never_use_product_identity_names` (`combat.rs`) — ни под одну
 * из 36 основ `FORBIDDEN_STEMS` и ни под одно из 9 слов `FORBIDDEN_WORDS` оно не
 * попадает.
 *
 * ЧТО ВЗЯТО ИЗ SRD, А ЧТО НАШЕ. Границу видно построчно:
 * - из открытого бестиария (`src-tauri/bestiary/bestiary.json`, запись `goblin`,
 *   подпись CC BY 4.0) взяты ровно четыре факта стат-блока: размер
 *   **Маленький**, **тёмное зрение 60 футов**, языки **Общий и Гоблинский** и
 *   особенность **«Ловкий побег»** (Отход или Засада бонусным действием). Это
 *   открытый контент, он взят как есть, и переписывать его своими словами
 *   значило бы завести вторую формулировку одного и того же правила;
 * - наше: бонусы характеристик, скорость, навык, который раса даёт сама, две
 *   особенности ниже («Пролезть куда угодно» и «Счёт обид»), вся проза, возраст,
 *   мировоззрение и рост.
 *
 * Играбельный гоблин из чужой книги как пакет здесь не воспроизводится. Его
 * бонусы характеристик, его скорость и его вторая особенность (ярость за
 * обиженного соплеменника, считающаяся от бонуса мастерства) не использованы:
 * совпадает только то, что лежит в открытом стат-блоке SRD-бестиария, и собрано
 * оно по-своему — «Счёт обид» платит преимуществом за память об одном
 * обидчике, а не за гибель союзника, и работает раз между длинными отдыхами.
 *
 * ЧЕГО У ЭТОЙ РАСЫ НЕТ И ПОЧЕМУ. Заклинаний она не даёт ни одного — значит
 * ни `spells.json`, ни заговоров расы её не касается. Скорость она объявляет
 * базой (`RACE_SPEED_FEET`), а не слоем к `effectiveStats.ts`: 25 футов — это
 * хранимое `Character.speedFeet`, а не пересчёт поверх него, поэтому у
 * эффективного значения листа по-прежнему один владелец и один порядок слоёв.
 */

