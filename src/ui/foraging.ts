/**
 * Сбор еды — НАШЕ правило, а не SRD.
 *
 * Происхождение названо прямо, как у `wildMagicSurges.ts` (таблица владельца) и
 * `abyssElfRace.ts` (наша играбельная раса): ПРАВИЛА сбора еды в завендоренном
 * SRD 5.1 нет.
 *
 * Сверено самостоятельно, и ответ точнее, чем «ноль вхождений»: само
 * словосочетание в `rules.json` встречается один раз — раздел «Расходы» говорит,
 * что персонажи «живут в глухой местности за счёт охоты и сбора еды». Это
 * описание быта: ни проверки, ни Сложности, ни выдачи там нет. Правила, которое
 * строка таблицы могла бы «снизить до 10», в источнике действительно не
 * существует, и сторожит это проба `foraging.test.ts`.
 *
 * Правило понадобилось строке 11 таблицы «Столкновения местности Подземья»
 * (`eventTables/underdarkTerrainEncounters.ts`): подземный ручей обещает, что
 * «Сложность проверки на сбор еды в этой зоне снижается до 10», а снижать было
 * нечего — обещание висело в воздухе. Решение владельца от 01.10.2026: заводим
 * своё правило отдельным файлом с объяснением происхождения, и строка начинает
 * работать.
 *
 * Что здесь наше, а что из SRD:
 * - СТУПЕНИ СЛОЖНОСТИ (20 / 15 / 10) и выдача «1к6 + модификатор Мудрости» —
 *   наши. Ни одного числа отсюда в `rules.json` не добавлено: граница «всё, что
 *   оттуда, — SRD» осталась проверяемой.
 * - А вот ЕДИНИЦЫ выдачи — из SRD: фунт еды и галлон воды это ровно суточная
 *   норма одного персонажа (`[3]/blocks[27]` и `[3]/blocks[31]`). Поэтому
 *   собранное считается в днях-персонах без всякого второго курса пересчёта:
 *   фунт = день еды одному, галлон = день воды одному.
 *
 * Строка таблицы остаётся ТЕКСТОМ: машиночитаемых эффектов у строк событий в
 * этой карточке не заводится (решение владельца 17.09.2026). Изобилие зоны
 * выбирает Мастер — тем же движением, каким он читает строку за столом.
 */

/** Изобилие зоны — три ступени, и Сложность у каждой своя. */
export type ForageAbundanceId = "scarce" | "ordinary" | "abundant";

export interface ForageZone {
  readonly id: ForageAbundanceId;
  readonly name: string;
  /** Сложность проверки Мудрости (Выживание). */
  readonly dc: number;
  /** За что эта ступень — словами, чтобы Мастер выбрал её не угадывая. */
  readonly note: string;
}

/**
 * Три ступени изобилия. Нижняя — ровно та «Сложность 10», которую обещает
 * подземный ручей: её сторожит проба, сверяющая число с текстом строки.
 */
export const FORAGE_ZONES: readonly ForageZone[] = [
  {
    id: "scarce",
    name: "Скудная",
    dc: 20,
    note: "Пустошь, глубокое подземелье, выжженная земля — съедобного почти нет",
  },
  {
    id: "ordinary",
    name: "Обычная",
    dc: 15,
    note: "Лес, луг, обжитые пещеры — обычная для странствий зона",
  },
  {
    id: "abundant",
    name: "Изобильная",
    dc: 10,
    note: "Рыбный ручей, грибная пещера, пойма реки — еда сама идёт в руки",
  },
];

/** Навык проверки: Мудрость (Выживание) — то же имя, что в списке навыков листа. */
export const FORAGE_SKILL = "Выживание";

/** Кость выдачи; модификатор Мудрости прибавляется к ней при успехе. */
export const FORAGE_YIELD_DIE = 6;

export function forageZoneById(id: string | null | undefined): ForageZone {
  return FORAGE_ZONES.find((zone) => zone.id === id) ?? FORAGE_ZONES[1];
}

/** Что дал один сбор еды за дневной привал. */
export interface ForageOutcome {
  success: boolean;
  /** Фунтов еды — по SRD это столько же дней еды на одного персонажа. */
  poundsOfFood: number;
  /** Галлонов воды — столько же дней воды на одного персонажа. */
  gallonsOfWater: number;
  reason: string;
}

/**
 * Итог сбора: проверка против Сложности зоны, при успехе — `1к6 + модификатор
 * Мудрости` фунтов еды и столько же галлонов воды, но не меньше одного фунта
 * (бросок 1 при отрицательном модификаторе иначе давал бы успех с пустыми
 * руками — успех, который ничего не значит, хуже провала).
 *
 * Бросок кости приходит СНАРУЖИ, как и проверка: кость в приложении бросает
 * движок (`roll_dice`), и своего генератора у этого файла нет.
 */
export function forageOutcome(
  checkTotal: number,
  dc: number,
  yieldRoll: number,
  wisdomMod: number,
): ForageOutcome {
  if (checkTotal < dc) {
    return {
      success: false,
      poundsOfFood: 0,
      gallonsOfWater: 0,
      reason: `Проверка ${FORAGE_SKILL} ${checkTotal} против Сложности ${dc} — съедобного не нашлось`,
    };
  }
  const amount = Math.max(1, yieldRoll + wisdomMod);
  return {
    success: true,
    poundsOfFood: amount,
    gallonsOfWater: amount,
    reason: `Проверка ${FORAGE_SKILL} ${checkTotal} против Сложности ${dc} — ${amount} фунт(ов) еды и ${amount} гал. воды`,
  };
}
