import { describe, expect, it } from "vitest";
import { JOURNAL_ENTRY_MAX_LENGTH, clampToLength, rowGist } from "./journalEntryText";

/**
 * Дефект, ради которого эти пробы существуют (владелец, 17.09.2026): кнопка
 * «В дневник» на «Приключениях» писала в кампанию строки таблиц целиком — до
 * 3043 символов при пределе в 100, — потому что предел был атрибутом
 * `maxLength` у формы дневника, а не правилом данных. Стили добивали такую
 * запись молча: `overflow: hidden` срезал всё лишнее без многоточия, и
 * прочитать остаток было нельзя никогда.
 */
describe("длина записи дневника", () => {
  it("предел — страничный, а не заметочный", () => {
    // Замерено на живом окне 1018x797: 550 знаков страница обрывает на
    // полуслове, 420 ложатся чисто и с запасом. Если число уедет вниз к
    // прежней сотне — вернётся обрезка сутью вместо целой записи; если вверх
    // к 550 — вернётся молчаливое обрезание страницей.
    expect(JOURNAL_ENTRY_MAX_LENGTH).toBe(420);
  });

  it("короткую строку не трогает вовсе", () => {
    expect(clampToLength("Бурлящая лава", 100)).toBe("Бурлящая лава");
  });

  it("обрезает по границе слова и ставит многоточие", () => {
    const result = clampToLength("Предупредительный знак дроу в сталагмитах", 25);

    expect(result.length).toBeLessThanOrEqual(25);
    expect(result.endsWith("…")).toBe(true);
    // Слово не разорвано посередине: обрывок «предупредительн…» читается хуже.
    expect(result).toBe("Предупредительный знак…");
  });

  it("не оставляет висящую запятую перед многоточием", () => {
    expect(clampToLength("Пещера в сталактитах, и на одном из столбов знак", 24)).toBe(
      "Пещера в сталактитах…",
    );
  });

  it("режет жёстко, если слово одно и длиннее предела", () => {
    const result = clampToLength("Длинноеслововообщебезпробелов", 10);

    expect(result).toHaveLength(10);
    expect(result.endsWith("…")).toBe(true);
  });

  it("сутью титрованной строки служит её заголовок", () => {
    expect(rowGist("Бурлящая лава. Пол коридора вздрагивает и лопается за спиной отряда.")).toBe(
      "Бурлящая лава",
    );
  });

  it("короткое первое предложение читается как заголовок, без точки", () => {
    // Порог заголовка — 60 знаков, и предложение в 50 под него попадает.
    // Разницы для сути нет: та же фраза, только без точки на конце.
    const text =
      "Персонажам нужна информация о чем-то ОЧЕНЬ редком. Найти её можно лишь у отшельника.";

    expect(rowGist(text)).toBe("Персонажам нужна информация о чем-то ОЧЕНЬ редком");
  });

  it("сутью длинной прозаической строки служит первое предложение целиком", () => {
    const text =
      "Треант-хранитель древнего леса пропал и теперь каста варденов ищет виноватых среди пришлых. " +
      "Отряду предлагают найти его прежде, чем начнётся расправа.";

    expect(rowGist(text)).toBe(
      "Треант-хранитель древнего леса пропал и теперь каста варденов ищет виноватых среди пришлых.",
    );
  });

  it("длинное первое предложение заголовком не считается", () => {
    // Иначе «суть» разрослась бы на всю страницу и смысла в ней не осталось.
    const long = `${"очень длинное начало без точки ".repeat(4)}. Дальше текст.`;

    expect(rowGist(long).length).toBeGreaterThan(60);
  });
});
