/**
 * Предел длины записи — ОДНА СТРАНИЦА разворота.
 *
 * Решение владельца 17.09.2026: «один блок — это полностью левая страница,
 * и туда можно будет записывать столько информации, сколько позволяет
 * уместить блок. А правая страница — это второй такой же блок». То есть
 * запись больше не обязана влезать в короткую заметку, но страница конечна,
 * и предел остаётся — просто страничный вместо прежних ста символов.
 *
 * Откуда число — ЗАМЕР НА ЖИВОМ ОКНЕ, а не арифметика. Считать по геометрии
 * я пробовал и промахнулся: вышло 550 при ~42 знаках в строке, а колонка на
 * деле держит ~35, и запись в 550 знаков обрывалась на полуслове. Проверено
 * двумя пробами в окне 1018x797: 550 режется страницей, 420 ложится чисто и
 * заканчивается с запасом в несколько строк.
 *
 * Запас оставлен намеренно. Страница держит около 540 знаков, но вместимость
 * плывёт: от ширины окна, от длины слов, от переносов. Сидеть вплотную к
 * границе — значит вернуть ровно тот дефект, который эта правка чинит, только
 * реже и незаметнее. Лучше срезать длинную запись честным многоточием, чем
 * дать странице съесть хвост молча.
 *
 * Менять это число можно только вместе с новым замером на живом окне. Шрифт,
 * поля, высота страницы и ширина колонки — всё на него влияет.
 */
export const JOURNAL_ENTRY_MAX_LENGTH = 420;

/** Многоточие приписывается, когда суть не поместилась целиком. Одним
 *  символом, а не тремя точками: он занимает одну позицию из бюджета. */
const ELLIPSIS = "…";

/**
 * Заголовок строки таблицы, если он есть.
 *
 * У части таблиц строка начинается с назывного предложения, которое и есть
 * суть события: «Бурлящая лава.», «Предупредительный знак.», «Фингум Стинкус
 * (Fyngum Stinkus).» У другой части (зацепки приключений, случайные события)
 * заголовка нет, строка сразу идёт прозой — там сутью служит первое
 * предложение.
 *
 * Нужно это стало реже, чем задумывалось: при страничном пределе почти все
 * строки помещаются целиком. Остаётся для длинных — зацепки приключений
 * доходят до 3043 символов и на страницу не влезут никогда.
 */
const MAX_TITLE_LENGTH = 60;

function leadingTitle(text: string): string | null {
  const match = /^([^.!?]{3,})[.!?](\s|$)/.exec(text);
  if (!match) return null;
  const title = match[1].trim();
  return title.length <= MAX_TITLE_LENGTH ? title : null;
}

function firstSentence(text: string): string {
  const match = /^(.*?[.!?])(\s|$)/s.exec(text);
  return (match ? match[1] : text).trim();
}

/**
 * Суть строки: заголовок, если он есть, иначе первое предложение.
 * Ничего не обрезает — обрезкой занимается вызывающий, который один знает,
 * сколько места осталось.
 */
export function rowGist(text: string): string {
  return leadingTitle(text) ?? firstSentence(text);
}

/**
 * Укорачивает строку до предела по границе слова.
 *
 * Режем по пробелу, а не посреди слова: обрывок «предупредительн…» читается
 * хуже, чем «предупредительный…». Если слово одно и оно длиннее предела —
 * режем жёстко, иначе вернули бы пустоту.
 */
export function clampToLength(text: string, limit: number): string {
  if (text.length <= limit) return text;
  const room = limit - ELLIPSIS.length;
  if (room <= 0) return ELLIPSIS.slice(0, limit);
  const cut = text.slice(0, room);
  const lastSpace = cut.lastIndexOf(" ");
  const body = lastSpace > room / 2 ? cut.slice(0, lastSpace) : cut;
  return body.replace(/[\s,;:—-]+$/u, "") + ELLIPSIS;
}
