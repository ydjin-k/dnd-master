/**
 * Последняя из пяти рас пачки B — «Дженази». Наша собственная, не SRD.
 *
 * ГДЕ ОНА ЖИВЁТ И ПОЧЕМУ ИМЕННО ЗДЕСЬ. Разобрано один раз и общо для всех наших
 * рас — `docs/design/own-races-how-to.md` и шапка `abyssElfRace.ts`. Коротко: в
 * `src-tauri/rules/rules.json` лежит ровно SRD 5.1, подвал вкладки «Правила»
 * обещает SRD за всё, что пришло оттуда, и раса, положенная в тот файл, молча
 * получила бы чужую подпись. Поэтому наша раса — отдельный модуль, а факт «это
 * наше» объявлен ровно в одном месте: `OWN_RULE_TOPICS` (`ownRuleTopics.ts`).
 *
 * ОТКУДА ВЗЯТО ИМЯ. Решение владельца 27.09.2026: имена десяти новых рас берутся
 * из его файлов («их брать можно, это информация в свободном доступе»), а
 * содержание пишется своё. Имя прогнано по сторожу
 * `own_creatures_never_use_product_identity_names` (`combat.rs`) — ни под одну
 * из 36 основ `FORBIDDEN_STEMS` и ни под одно из 9 слов `FORBIDDEN_WORDS` оно не
 * попадает.
 *
 * ОДНА РАСА, ЧЕТЫРЕ СТИХИИ — решение владельца 07.10.2026, и оно здесь главное.
 * Раса одна: одна строка в `OWN_RULE_TOPICS`, один модуль, один набор бонусов,
 * одна скорость, один навык и один список языков. Разную механику дают СТИХИИ
 * (`GENASI_ELEMENTS` ниже): каждая добавляет к общим особенностям свои две.
 * Механизма выбора варианта расы в мастере не было ни у одной расы — его
 * заводит эта раса, и устройство разобрано у владельца механизма
 * (`RACE_VARIANTS` в `characterCreationData.ts`).
 *
 * ЧЕГО СТИХИЯ НЕ МЕНЯЕТ, И ЭТО СОЗНАТЕЛЬНО. Ни бонусов характеристик, ни
 * скорости, ни навыка, ни языков. У чужой расы той же ниши каждая подраса
 * добавляет свой +1 к характеристике — и это ровно тот путь, на котором одна
 * раса превращается в четыре. Выбор здесь меняет НАБОР ОСОБЕННОСТЕЙ, как и
 * просит карточка: шаг «Характеристики» о стихии не знает вовсе, и ни одной
 * ветки «а если стихия такая» в расчётах не появляется.
 *
 * ЧТО ВЗЯТО ИЗ SRD, А ЧТО НАШЕ. Границу видно построчно:
 * - **язык Первичный** стоит в списке языков SRD (`ALL_LANGUAGES`,
 *   `characterCreationData.ts`) и в открытом стат-блоке `night-hag`; два его
 *   наречия — **Игнан** и **Акван** — стоят в открытом бестиарии (CC BY 4.0)
 *   у семи стат-блоков каждое (`magmin`, `azer`, `fire-elemental`,
 *   `salamander`, `efreeti` и соседи; `merfolk`, `water-elemental`,
 *   `dragon-turtle` и соседи). Один язык и четыре наречия — это и есть повод
 *   дать расе четыре стихии при одном языке;
 * - **«дышать воздухом и водой»** — формулировка открытой особенности
 *   «Амфибия» (`merfolk`, `frog`, `chuul` и соседи), и стихия воды повторяет
 *   её, а не заводит вторую формулировку того же правила;
 * - из открытого SRD (`rules.json`) взяты два правила, на которые стихии
 *   ссылаются: **задержка дыхания** (там она считается от Телосложения) и
 *   **«сбить его с ног или оттолкнуть от себя»** — приём рукопашной атаки;
 * - наше: бонусы характеристик, скорость, размер, навык, который раса даёт
 *   сама, три общих особенности, все восемь особенностей стихий, вся проза,
 *   все четыре таблицы, возраст, мировоззрение и рост.
 *
 * Играбельный дженази из чужой книги как пакет здесь не воспроизводится.
 * Оттуда не взято НИ ОДНОГО числа и ни одной черты: у чужой расы Телосложение
 * +2 плюс свой +1 у каждой подрасы, рост от 5 до 6 футов, 120 лет жизни, и
 * каждая подраса раздаёт заклинания — левитацию, бесследное передвижение,
 * огненные ладони с заговором, сотворение или уничтожение воды с заговором, —
 * плюс тёмное зрение, сопротивление огню, сопротивление кислоте и скорость
 * плавания. Здесь бонус один на расу и Харизма вместо подрасовых прибавок,
 * рост и срок жизни свои, заклинаний нет ни одного, тёмного зрения нет,
 * сопротивлений нет, скорость плавания не заводится.
 *
 * ПОЧЕМУ БОНУС ИМЕННО ТАКОЙ. Телосложение — стихия в плоти, и деться ему
 * некуда: у чужой расы общая прибавка стоит там же, потому что у стихийного
 * тела другого места нет. Расхождение проверяемо ПАРОЙ: все четыре чужих
 * подрасы дают Телосложение с Ловкостью, Силой, Интеллектом или Мудростью, и
 * ни одна — с Харизмой. Пара заодно разошлась с нашими Серпентами
 * (Телосложение +2 и Интеллект +1) и с девятью расами SRD.
 *
 * ЧЕГО У ЭТОЙ РАСЫ НЕТ И ПОЧЕМУ. Заклинаний она не даёт ни одного, и у этой
 * расы потеря самая заметная: в чужом пакете заклинание есть у каждой из
 * четырёх подрас. Взять их нельзя — раздатчики заговоров и расовых ячеек
 * сегодня умеют ровно одну расу (Эльфа бездны), обобщать их — отдельная
 * карточка, а дописать ветку в `abyssElfRace.ts` значило бы сделать файл Эльфа
 * бездны владельцем чужих фактов. Поэтому стихии закрыты особенностями.
 *
 * Тёмного зрения нет, и причина НЕ в том, что его негде взять: у открытых
 * стихийных стат-блоков оно как раз есть — 60 футов у `fire-elemental`,
 * `water-elemental`, `air-elemental`, `earth-elemental`, `magmin` и
 * `salamander`. Причин две, и обе проверяемы. Первая: единого числа всё равно
 * нет — у открытых гениев (`efreeti`, `djinni`), то есть у РОДИТЕЛЯ дженази по
 * этой нише, стоит 120 футов, и «как у родителя» дало бы расе дальность выше,
 * чем у любой нашей расы, а «как у элементаля» — число не того предка.
 * Вторая: дальность 60 футов в наших расах уже держат трое (Гоблин, Серпенты,
 * Табакси), и четвёртая копия сделала бы её общей приметой наших рас вместо
 * приметы расы — тот же довод, по которому Аасимар не взял «Сопротивление
 * магии». Скорости плавания нет: `Character.speedFeet` — одно число с одним
 * владельцем, и второй скорости в листе сегодня нет места. Прибавки к хитам
 * нет. Скорость раса объявляет базой (`RACE_SPEED_FEET`), а не слоем к
 * `effectiveStats.ts`.
 */

