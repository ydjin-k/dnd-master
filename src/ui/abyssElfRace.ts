/**
 * Десятая раса приложения — «Эльф бездны». Наша собственная, не SRD.
 *
 * ГДЕ ОНА ЖИВЁТ И ПОЧЕМУ ИМЕННО ЗДЕСЬ. Девять остальных рас приезжают из
 * `src-tauri/rules/rules.json`, и туда эта раса НЕ положена. В rules.json лежит
 * ровно SRD 5.1 под своей лицензией и своей атрибуцией — это проверяемая
 * граница проекта: «всё, что пришло из rules.json, — SRD». Подмешать туда
 * собственный контент значит сделать границу непроверяемой ничем, кроме
 * памяти того, кто её подмешивал. Тот же довод уже отработан на таблице дикой
 * магии (`wildMagicSurges.ts`), и раса идёт его же дорогой: наше содержание —
 * отдельным файлом, в котором сказано, что оно наше.
 *
 * Есть и вторая, показательная причина, не только лицензионная. Вкладка
 * «Правила» (`pages/RulesPage.tsx`) показывает ВСЁ, что пришло из rules.json,
 * и подписывает показанное одним подвалом: «Текст правил — перевод SRD 5.1…
 * CC BY-NC-SA 4.0». Раса, попавшая в тот же список, получила бы эту подпись
 * молча и соврала бы игроку об источнике. Поэтому «Эльф бездны» попадает
 * только туда, где спрашивают «кем можно играть», — в мастер создания
 * (`playableRaces` ниже), а справочник SRD остаётся справочником SRD.
 *
 * ФОРМА. Раса собрана как обычный `RuleTopic` — та же форма, что у девяти
 * соседей, поэтому мастер создания показывает её тем же кодом, тем же
 * `RuleBlockView`, и никакой ветки «а вот эта раса особенная» в нём нет.
 * Отличается только происхождение данных, и ровно в одном месте —
 * `playableRaces`.
 *
 * ЧТО ВЗЯТО ИЗ SRD, А ЧТО НАШЕ. Границу видно построчно:
 * - из SRD 5.1 (стат-блок drider, он же «Elf, Drow»): «Superior Darkvision
 *   120 ft.» и «Sunlight Sensitivity» — это открытый контент, и они взяты как
 *   есть;
 * - из SRD 5.1 — три заклинания, и они уже наши же: `dancing-lights`,
 *   `faerie-fire`, `darkness` лежат в `spells.json` и берутся ССЫЛКОЙ ПО id,
 *   а не пересказом текста (у заклинания один владелец — `spells.json`);
 * - наше: бонусы характеристик, лесенка уровней, частота применения, цена,
 *   языки, скорость, вся проза ниже и имена.
 *
 * Играбельная раса дроу из Книги игрока как пакет здесь не воспроизводится:
 * её бонусы характеристик, её уровни открытия заклинаний и её формулировки не
 * использованы. Совпадают только те компоненты, которые лежат в открытом SRD,
 * — и они собраны по-своему (см. `ABYSS_CALL_RESOURCE_ID`: общий запас на два
 * заклинания вместо «каждое по разу в день», и оба доступны с 1 уровня).
 *
 * Слово «дроу» в проекте не запрещено — в SRD есть стат-блок «Elf, Drow» под
 * CC-BY. Раса называется иначе по содержательной причине: механики у неё свои,
 * и назвать её «дроу» значило бы пообещать игроку книжного дроу и выдать другое.
 */

