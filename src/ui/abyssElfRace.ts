/** Раса персонажа — наша? Ключ — НАЗВАНИЕ: `Character.race` хранит его, а не id. */
export function isAbyssElf(raceTitle: string | null | undefined): boolean {
  return raceTitle === ABYSS_ELF_TITLE;
}

/**
 * Полный список рас для мастера создания: девять из справочника SRD плюс наша
 * десятая. Единственное место, где наша раса встаёт в один ряд с остальными, —
 * и единственный владелец факта «кем можно играть».
 *
 * `races-traits` из справочника выброшен здесь же: это общая статья
 * «Расовые особенности», а не раса, и играть ею нельзя.
 */
export function playableRaces(topics: RuleTopic[]): RuleTopic[] {
  const srdRaces = topics.filter((t) => t.category === "races" && t.id !== "races-traits");
  return [...srdRaces, ABYSS_ELF_TOPIC];
}

/** Заговоры, которые раса даёт сама (без выбора игрока и сверх нормы класса). */
export function raceGrantedCantrips(raceTitle: string | null | undefined): string[] {
  return isAbyssElf(raceTitle) ? [ABYSS_ELF_CANTRIP_ID] : [];
}

/**
 * Ограниченные ресурсы, которые даёт раса, — той же формы, что классовые
 * (`ClassResource`), поэтому счётчик, кнопки «Потратить»/«Восстановить» и
 * запись в `Character.featureUses` работают уже существующим кодом.
 *
 * Максимум зависит от уровня — это наша лесенка, а не таблица класса, поэтому
 * уровень приходит параметром, а не берётся из `progressionAt`.
 */
