/**
 * Строка «какие это заклинания» — единственное место, где они называются
 * игроку по именам, и имена берутся не отсюда: `spellName` разрешает id через
 * `spells.json`, владельца названия. Поэтому в особенностях выше имён нет
 * вовсе — второй копии, расходящейся при переименовании, не заводится.
 *
 * `null` у всех остальных рас: показывать нечего.
 */
export function abyssElfSpellLine(
  raceTitle: string | null | undefined,
  spellName: (id: string) => string,
): string | null {
  if (!isAbyssElf(raceTitle)) return null;
  const [faerieFire, darkness] = ABYSS_CALL_SPELL_IDS;
  return `Заклинания расы: ${spellName(ABYSS_ELF_CANTRIP_ID)} — заговор, без ограничений; ${spellName(
    faerieFire,
  )} и ${spellName(darkness)} — из запаса «Зова бездны», без ячейки.`;
}

