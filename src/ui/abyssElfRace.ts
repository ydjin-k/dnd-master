/** Раса персонажа — наша? Ключ — НАЗВАНИЕ: `Character.race` хранит его, а не id. */
export function isAbyssElf(raceTitle: string | null | undefined): boolean {
  return raceTitle === ABYSS_ELF_TITLE;
}

/** Заговоры, которые раса даёт сама (без выбора игрока и сверх нормы класса). */
