/**
 * Строка таблицы. Диапазон включительный с обеих сторон; у строки, которая
 * покрывает одно число, `from === to`. Диапазоны нужны не про запас: в
 * переданных документах встречается вёрстка вида «1-15 / 16-20», и строка
 * броска там покрывает промежуток, а не одно число.
 */
export interface EventTableRow {
  readonly from: number;
  readonly to: number;
  readonly text: string;
  /** Существа из `bestiary.json`, которых строка ставит на стол. */
  readonly monsterIds?: readonly string[];
  /**
   * Таблицы, в которые строка отправляет бросок дальше, — по `id`.
   *
   * Заведено под распределитель столкновений Подземья: до него строка была
   * сама себе результатом, а он сам по себе не результат и обязан послать
   * бросок в таблицу местности, в таблицу существ или в обе сразу.
   *
   * ВТОРОГО МЕХАНИЗМА БРОСКА ЗДЕСЬ НЕТ и заводить его нельзя: названная
   * таблица бросается тем же `roll_dice` и разбирается тем же `rowForRoll`,
   * что и первая. Поле задаёт только порядок, а не способ.
   *
   * Порядок значим: результаты выходят на экран цепочкой в том же порядке,
   * каждый со своим числом и своей костью, и НЕ сливаются в один. Два
   * столкновения в исходнике — два результата у игрока.
   */
  readonly rollTableIds?: readonly string[];
  /**
   * Заклинания из `rules/spells.json`, чьим эффектом строка описывает своё
   * действие. Строка ссылается на `id` и не пересказывает заклинание своими
   * словами: у эффекта один владелец, и это `spells.json`.
   */
  readonly spellIds?: readonly string[];
}

export interface EventTable {
  readonly id: string;
  readonly name: string;
  /** Раздел в списке выбора; порядок разделов держит `TABLE_GROUPS`. */
  readonly group: string;
  /**
   * Число граней. **Задаёт таблица, а не вызывающий код**: у переданных
   * документов кость разная — от d6 у «NPC / Юмор» до d150 у сюжетных
   * поворотов, и генератор обязан читать её отсюда.
   */
  readonly die: number;
  readonly source: string;
  /** Что сделано с таблицей при переносе, если она перенесена не целиком. */
  readonly sourceNote?: string;
  readonly rows: readonly EventTableRow[];
}
