export const OWNER_SUPPLIED =
  "Передано владельцем 16.09.2026; пометок авторства в исходнике нет";

/**
 * Строка таблицы. Диапазон включительный с обеих сторон; у строки, которая
 * покрывает одно число, `from === to`. Диапазоны нужны не про запас: в
 * переданных документах встречается вёрстка вида «1-15 / 16-20», и строка
 * броска там покрывает промежуток, а не одно число.
 */
export interface EventTableRow {
  readonly from: number;
  readonly to: number;
  readonly text: string;
  /** Существа из `bestiary.json`, которых строка ставит на стол. */
  readonly monsterIds?: readonly string[];
}

export interface EventTable {
  readonly id: string;
  readonly name: string;
  /** Раздел в списке выбора; порядок разделов держит `TABLE_GROUPS`. */
  readonly group: string;
  /**
   * Число граней. **Задаёт таблица, а не вызывающий код**: у переданных
   * документов кость разная — от d6 у «NPC / Юмор» до d150 у сюжетных
   * поворотов, и генератор обязан читать её отсюда.
   */
  readonly die: number;
  readonly source: string;
  /** Что сделано с таблицей при переносе, если она перенесена не целиком. */
  readonly sourceNote?: string;
  readonly rows: readonly EventTableRow[];
}
