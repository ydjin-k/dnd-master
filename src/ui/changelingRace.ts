/**
 * Раса «Чейнджлинг». Наша собственная, не SRD.
 *
 * ГДЕ ОНА ЖИВЁТ И ПОЧЕМУ ИМЕННО ЗДЕСЬ. Общий разбор — `docs/design/own-races-how-to.md`
 * и шапка `abyssElfRace.ts`. Коротко: в `src-tauri/rules/rules.json` лежит ровно
 * SRD 5.1, подвал вкладки «Правила» обещает SRD за всё пришедшее оттуда, и
 * раса, положенная в тот файл, молча получила бы чужую подпись. Поэтому раса —
 * отдельный модуль, а факт «это наше» объявлен ровно в одном месте:
 * `OWN_RULE_TOPICS` (`ownRuleTopics.ts`).
 *
 * ОТКУДА ВЗЯТО ИМЯ. Решение владельца 27.09.2026: имена берутся из его файлов,
 * содержание пишется своё. Имя прогнано по сторожу
 * `own_creatures_never_use_product_identity_names` (`combat.rs`) — ни под одну
 * из 36 основ `FORBIDDEN_STEMS` и ни под одно из 9 слов `FORBIDDEN_WORDS` оно не
 * попадает.
 *
 * ЧТО ВЗЯТО ИЗ SRD, А ЧТО НАШЕ. Здесь раздел короткий, и это честный ответ, а
 * не пропуск:
 * - из SRD 5.1 — **НИЧЕГО**. Ни формулировки, ни числа, ни заклинания. В
 *   открытом SRD нет ни играбельной расы этой ниши, ни стат-блока меняющего
 *   облик гуманоида, у которого можно было бы взять механику открытым текстом,
 *   как взяты «Ловкий побег» у Гоблина и «Сопротивление магии» у Сатира;
 * - наше: **всё** — бонусы характеристик, скорость, языки и их число, навык,
 *   четыре особенности ниже, вся проза, возраст, мировоззрение и рост.
 *
 * Играбельный чейнджлинг из чужой книги как пакет здесь не воспроизводится.
 * Его бонус «+1 в характеристику по вашему выбору» не использован (у нас оба
 * бонуса фиксированы), его два навыка по выбору не использованы, и смена облика
 * у нас стоит игроку цены, которой у чужой расы нет: в истинном виде
 * чейнджлинга узнают, и «Обман» в нём идёт с помехой. Из файла владельца взяты
 * только ниша (скрытный народ, живущий среди чужих) и облик истинной формы —
 * бесцветная кожа, светлые глаза, серебряные волосы.
 *
 * ЧЕГО У ЭТОЙ РАСЫ НЕТ И ПОЧЕМУ. Смена облика здесь — особенность, а НЕ
 * заклинание: заклинаний раса не даёт ни одного, поэтому ни `spells.json`, ни
 * заговоров расы она не касается и второго владельца заклинания не появляется.
 * Тем же приёмом устроен «Меняющий облик» у наших серпентов в бестиарии
 * (`own-creatures.json`) — это уже заведённый в проекте способ описать смену
 * облика, и раса идёт его дорогой. Скорость объявлена БАЗОЙ
 * (`RACE_SPEED_FEET`), а не слоем к `effectiveStats.ts`.
 */

/** Идентификатор темы. Префикс `races-` — как у девяти соседей SRD. */
