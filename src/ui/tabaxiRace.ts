/**
 * Одна из пяти рас пачки B — «Табакси». Наша собственная, не SRD.
 *
 * ГДЕ ОНА ЖИВЁТ И ПОЧЕМУ ИМЕННО ЗДЕСЬ. Разобрано один раз и общо для всех наших
 * рас — `docs/design/own-races-how-to.md` и шапка `abyssElfRace.ts`. Коротко: в
 * `src-tauri/rules/rules.json` лежит ровно SRD 5.1, подвал вкладки «Правила»
 * обещает SRD за всё, что пришло оттуда, и раса, положенная в тот файл, молча
 * получила бы чужую подпись. Поэтому наша раса — отдельный модуль, а факт «это
 * наше» объявлен ровно в одном месте: `OWN_RULE_TOPICS` (`ownRuleTopics.ts`).
 *
 * ОТКУДА ВЗЯТО ИМЯ. Решение владельца 27.09.2026: имена десяти новых рас берутся
 * из его файлов («их брать можно, это информация в свободном доступе»), а
 * содержание пишется своё. Имя прогнано по сторожу
 * `own_creatures_never_use_product_identity_names` (`combat.rs`) — ни под одну
 * из 36 основ `FORBIDDEN_STEMS` и ни под одно из 9 слов `FORBIDDEN_WORDS` оно не
 * попадает.
 *
 * ЧТО ВЗЯТО ИЗ SRD, А ЧТО НАШЕ. Границу видно построчно:
 * - из открытого бестиария (`src-tauri/bestiary/bestiary.json`, запись `tiger`,
 *   подпись CC BY 4.0) взят один факт: **тёмное зрение 60 футов**. Это
 *   единственный кошачий стат-блок открытого бестиария, у которого чувство с
 *   дальностью есть вовсе (у `cat`, `panther` и `saber-toothed-tiger` строка
 *   чувств пуста), и число взято у него, а не подобрано по соседям;
 * - формулировка тёмного зрения взята из `rules.json` (SRD 5.1, абзац
 *   «Тёмное зрение» у эльфа) без вступительной фразы про сумрак леса: это
 *   открытый текст, и переписывать его своими словами значило бы завести
 *   вторую формулировку одного и того же правила;
 * - из SRD взят механизм выбора языка (`choiceCount: 1`) — тот же, что у
 *   Человека и Эльфа; у нашей расы он объясняется дорогой, а не книжной
 *   строкой;
 * - наше: бонусы характеристик, скорость, размер, навык, который раса даёт
 *   сама, две особенности ниже («Падение на лапы» и «Чутьё на новое»), вся
 *   проза, все четыре таблицы, возраст, мировоззрение и рост.
 *
 * Играбельный табакси из чужой книги как пакет здесь не воспроизводится. Его
 * бонусы характеристик (Ловкость и Харизма), его два фиксированных навыка, его
 * скорость лазания 20 футов, его когти как природное оружие на 1к4 и его
 * удвоение скорости на ход не использованы ни одним числом: из кошачьей ниши
 * взято тёмное зрение открытого стат-блока, а собрано оно по-своему —
 * «Падение на лапы» платит костью урона от падения, которой у чужой расы нет
 * вовсе, а «Чутьё на новое» привязано к осмотру незнакомого, а не к бою.
 *
 * ЧЕГО У ЭТОЙ РАСЫ НЕТ И ПОЧЕМУ. Заклинаний она не даёт ни одного — значит ни
 * `spells.json`, ни заговоров расы её не касается (раздатчики заговоров сегодня
 * умеют ровно одну расу, Эльфа бездны, и обобщать их — чужая карточка, см.
 * `own-races-how-to.md`). Прибавки к хитам у неё нет: `RACE_HP_BONUS` держит
 * расу, у которой прибавка и есть главная черта, а здесь главное — чутьё.
 * Скорость она объявляет базой (`RACE_SPEED_FEET`), а не слоем к
 * `effectiveStats.ts`.
 */

