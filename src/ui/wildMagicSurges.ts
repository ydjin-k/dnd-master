/** Сколько строк в таблице на самом деле. Сверяется с `WILD_MAGIC_DIE` пробой покрытия. */
export const WILD_MAGIC_TABLE_SIZE = WILD_MAGIC_TABLE.length;

/** Выпавшая строка: сама строка плюс её номер 1..WILD_MAGIC_DIE — то, что видит игрок. */
export interface WildMagicSurge extends WildMagicRow {
  roll: number;
}

/**
 * Итог попытки всплеска. `cantrip` — заговор всплеска не даёт вовсе,
 * `same-turn` — в этот ход бросок уже был, `calm` — бросок сделан и не выпал,
 * `surge` — выпал, и вот строка.
 */
export type WildMagicAttempt =
  | { kind: "cantrip" }
  | { kind: "same-turn" }
  | { kind: "calm"; d20: number }
  | { kind: "surge"; d20: number; surge: WildMagicSurge };

/** Что лист помнит между бросками: ход, в который бросок уже сделан. В сейв не попадает. */
export interface WildMagicTurnState {
  rolledTurnKey: string | null;
}

export const NO_WILD_MAGIC_TURN: WildMagicTurnState = { rolledTurnKey: null };

/** Архетип, у которого есть таблица. Сравнение имени в одном месте, а не в каждом экране. */
export function isWildMagicSorcerer(subclassName: string | null | undefined): boolean {
  return subclassName === WILD_MAGIC_SUBCLASS_NAME;
}

/**
 * Ключ хода для ограничения «не чаще раза за ход»: раунд и место в очереди
 * идущего боя. Вне боя ходов нет вовсе (`null`) — там ограничивать нечего, и
 * бросок делается на каждое наложенное заклинание.
 */
export function wildMagicTurnKey(combat: CombatState | null | undefined): string | null {
  if (!combat || combat.finished) return null;
  return `${combat.round}:${combat.currentTurnIndex}`;
}

/**
 * Бросок по таблице: к100, и номер кости — это номер строки. Единственный
 * владелец случайности всплеска: игрок строку не выбирает и вручную не
 * бросает. Результат всегда в границах кости, даже если `random` вернёт ровно
 * 1 (Math.random так не делает, но подменённый в пробе — может).
 */
export function rollWildMagicSurge(random: () => number = Math.random): WildMagicSurge {
  const roll = Math.min(WILD_MAGIC_DIE, Math.max(1, Math.floor(random() * WILD_MAGIC_DIE) + 1));
  return { roll, ...WILD_MAGIC_TABLE[roll - 1] };
}

/**
 * Попытка всплеска при наложении заклинания. Бросает движок: сначала к20 на
 * триггер, и только если выпало не больше `WILD_MAGIC_TRIGGER_MAX` — второй
 * бросок по таблице.
 *
 * Возвращает и новое состояние хода: за один ход бросок делается один раз,
 * сколько бы заклинаний в этот ход ни наложили.
 */
export function attemptWildMagicSurge({
  circle,
  turnKey,
  turnState,
  random = Math.random,
}: {
  /** Круг наложенного заклинания; заговор (0) всплеска не даёт. */
  circle: number;
  /** Ключ текущего хода или `null` вне боя (см. `wildMagicTurnKey`). */
  turnKey: string | null;
  turnState: WildMagicTurnState;
  random?: () => number;
}): { attempt: WildMagicAttempt; turnState: WildMagicTurnState } {
  if (circle < 1) return { attempt: { kind: "cantrip" }, turnState };
  if (turnKey !== null && turnState.rolledTurnKey === turnKey) {
    return { attempt: { kind: "same-turn" }, turnState };
  }
  const nextTurnState: WildMagicTurnState = { rolledTurnKey: turnKey };
  const d20 = Math.min(WILD_MAGIC_TRIGGER_DIE, Math.max(1, Math.floor(random() * WILD_MAGIC_TRIGGER_DIE) + 1));
  if (d20 > WILD_MAGIC_TRIGGER_MAX) return { attempt: { kind: "calm", d20 }, turnState: nextTurnState };
  return { attempt: { kind: "surge", d20, surge: rollWildMagicSurge(random) }, turnState: nextTurnState };
}
