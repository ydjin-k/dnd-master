/**
 * Таблица дикой магии чародея и весь механизм всплеска: бросок, триггер и
 * ограничение «не чаще раза за ход». Отдельный файл, а не строка в
 * `src-tauri/rules/rules.json`, намеренно: в rules.json лежит SRD 5.1, и
 * подмешивание туда собственного содержания сделало бы границу «у нас только
 * SRD» непроверяемой. Здесь — наше, написанное с нуля.
 *
 * Таблицы дикой магии в SRD 5.1 нет вовсе (у чародея там одно происхождение —
 * Драконья кровь), а книжную брать нельзя. Поэтому все 50 строк придуманы под
 * этот проект. Там, где эффект совпадает с заклинанием, которое у нас УЖЕ
 * описано, строка ссылается на его `id` в `spells.json` (`spellId`) и не
 * пересказывает его текст своими словами — у факта один владелец.
 *
 * Строки описательные — тот же принцип, что у `descriptive` в `SubclassEffect`:
 * движок бросает и показывает выпавшее, а применяют его за столом. Пятидесяти
 * видов эффекта под это не заводится.
 */

