/** Абзацы особенностей одной специализации: «Имя (N уровень). Текст.» — из тех же данных, что архетип. */
function specializationBlocks(spec: ClassSubclass): RuleBlock[] {
  const blocks: RuleBlock[] = [
    { type: "heading", level: 3, text: spec.name },
    { type: "paragraph", text: spec.description ?? "" },
  ];
  for (const [level, features] of Object.entries(spec.featuresByLevel)) {
    for (const feature of features) {
      blocks.push({ type: "paragraph", text: `${feature.name} (${level} уровень). ${feature.description}` });
    }
  }
  blocks.push({
    type: "paragraph",
    text: `На 18 уровне — «${SPECIALIZATION_LEVEL_18[spec.name]}», выше нынешнего потолка приложения.`,
  });
  return blocks;
}

