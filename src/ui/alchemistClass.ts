/** «Зелье лазания (1 к.)» — строка зелья для текстов: имя и цена в костях реагентов. */
function potionLine(potion: AlchemistPotion): string {
  return `${potion.name} (${potion.dice} к.)`;
}

/** Зелья ряда, открывающегося ровно на уровне `level`, одной строкой. */
export function potionsOpenedAt(level: number): string {
  return ALCHEMIST_POTIONS.filter((p) => p.minLevel === level).map(potionLine).join(", ");
}

