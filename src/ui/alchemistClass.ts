/** Уровень, с которого у алхимика есть кости реагентов (с. 1, 4 PDF). */
export const REAGENT_DICE_LEVEL = 3;

/**
 * Число костей реагентов на уровне (с. 1 PDF, столбец «Кости реагентов»):
 * 3к10 на 3 уровне и по одной кости за каждый следующий — то есть ровно
 * уровень алхимика. До 3 уровня костей нет.
 */
export function reagentDiceAt(level: number): number {
  return level >= REAGENT_DICE_LEVEL ? level : 0;
}

/**
 * Сколько бомб алхимик собирает за короткий или длинный отдых (с. 2 PDF,
 * умение «Бомбы»): 10 + удвоенный уровень алхимика.
 */
export function bombsAt(level: number): number {
  return 10 + 2 * level;
}

