/**
 * Последняя подошедшая ступень лесенки «с какого уровня → сколько всего»; 0 —
 * ниже первой ступени. То же правило, что `classChoiceKnownAt` общего
 * механизма, но без импорта значения: этот файл берёт оттуда только типы.
 */
export function knownAt(steps: readonly (readonly [number, number])[], level: number): number {
  let known = 0;
  for (const [from, count] of steps) {
    if (level >= from) known = count;
  }
  return known;
}

/** Строка таблицы уровней для статьи. Числа — те же владельцы, что кормят лист. */
function levelTableRow(level: number, features: string): string[] {
  const formulas = knownAt(BOMB_FORMULAS_KNOWN_STEPS, level);
  const discoveries = knownAt(DISCOVERIES_KNOWN_STEPS, level);
  const reagents = reagentDiceAt(level);
  return [
    String(level),
    `+${2 + Math.floor((level - 1) / 4)}`,
    formulas ? String(formulas) : "—",
    reagents > 0 ? `${reagents}к10` : "—",
    discoveries ? String(discoveries) : "—",
    features,
  ];
}

