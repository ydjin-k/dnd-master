import type { DungeonRecord } from "../../state/types";

/**
 * Заметки мастера к комнатам и отметкам подземелья.
 *
 * Здесь живут ВСЕ правила заметки: чем она пуста, когда исчезает из записи, у
 * кого она есть и сколько их в подземелье. Поле ввода (`NoteField`) и экраны
 * эти функции только зовут, своего понятия «пусто» не заводя.
 *
 * Ключ — тот же `id`, под которым лежит статус: `trap-1`, `door-3` у отметок и
 * `room-4` из `roomKey` у комнат. Второго пространства имён заметки не
 * заводят, поэтому одна комната не может оказаться «той же» для статуса и
 * «другой» для заметки.
 */

/** Заметка к отметке или комнате; у записи без заметок — пустая строка. */
export function noteOf(dungeon: DungeonRecord, id: string): string {
  return dungeon.notes?.[id] ?? "";
}

/** У отметки или комнаты есть заметка — на схеме у неё признак. */
export function hasNote(dungeon: DungeonRecord, id: string): boolean {
  return noteOf(dungeon, id).trim().length > 0;
}

/** Сколько заметок в записи: перечень «Пересобрать» обязан их назвать. */
export function noteCount(dungeon: DungeonRecord): number {
  return Object.keys(dungeon.notes ?? {}).length;
}

/**
 * Подземелье с новой заметкой под ключом `id`.
 *
 * Пустая заметка (и заметка из одних пробелов) из записи УДАЛЯЕТСЯ, а не
 * ложится пустой строкой: иначе мастер, стерший текст, оставлял бы в кампании
 * пустой ключ — и «Пересобрать» честно предупреждало бы о пропаже заметок,
 * которых нет, а вид для игроков принимал бы такую комнату за помеченную.
 *
 * Текст пишется как набран, пробелы по краям не срезаются: поле управляемое, и
 * подрезка на каждом нажатии не дала бы поставить пробел между словами. Решает
 * «пусто ли» всё равно `trim`, так что заметка из пробелов в запись не попадёт.
 */
export function withNote(dungeon: DungeonRecord, id: string, text: string): DungeonRecord {
  const notes = { ...(dungeon.notes ?? {}) };
  if (text.trim().length === 0) delete notes[id];
  else notes[id] = text;
  return { ...dungeon, notes };
}
