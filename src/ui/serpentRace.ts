/**
 * Раса «Серпенты». Наша собственная, не SRD.
 *
 * ГДЕ ОНА ЖИВЁТ И ПОЧЕМУ ИМЕННО ЗДЕСЬ. Общий разбор — `docs/design/own-races-how-to.md`
 * и шапка `abyssElfRace.ts`. Коротко: в `src-tauri/rules/rules.json` лежит ровно
 * SRD 5.1, подвал вкладки «Правила» обещает SRD за всё пришедшее оттуда, и
 * раса, положенная в тот файл, молча получила бы чужую подпись. Поэтому раса —
 * отдельный модуль, а факт «это наше» объявлен ровно в одном месте:
 * `OWN_RULE_TOPICS` (`ownRuleTopics.ts`).
 *
 * ОТКУДА ВЗЯТО ИМЯ. Имя «Серпенты» дано владельцем 23.09.2026, и оно СВОЁ с
 * самого начала: оно не из чужой книги, а заменило чужое имя в нашем бестиарии.
 * Три записи с ним уже живут в `src-tauri/bestiary/own-creatures.json`
 * (`chistokrovny-serpent`, `polukrovny-serpent`, `otrodye-serpenta`). Основы
 * чужого имени, под которыми сторож `own_creatures_never_use_product_identity_names`
 * держал бы эту нишу, сняты из списка решением владельца 27.09.2026 вместе с
 * принятием имени; само имя по 36 основам `FORBIDDEN_STEMS` и 9 словам
 * `FORBIDDEN_WORDS` прогнано и ни под одно не попадает.
 *
 * ЧТО ВЗЯТО ИЗ SRD, А ЧТО НАШЕ. Здесь граница проходит не там, где у Гоблина и
 * Сатира: у этой расы в проекте уже есть СВОИ существа, и раса согласована с
 * ними, а не с чужой книгой.
 * - из открытого SRD взята одна формулировка — **«Сопротивление магии»**
 *   (преимущество на спасброски против заклинаний и прочих магических
 *   эффектов). Она стоит в открытых стат-блоках SRD (например, у `satyr` в
 *   `bestiary.json`), взята как есть, и вторая её формулировка разошлась бы с
 *   первой;
 * - из НАШЕГО бестиария (`own-creatures.json`, записи серпентов) взяты
 *   **тёмное зрение 60 футов** и **языки Бездны, Драконий и Общий**: это не
 *   SRD и не чужая книга, а согласование расы с уже написанными нами
 *   существами. Разойдись эти два факта — игрок увидел бы в бестиарии одного
 *   серпента, а в мастере другого;
 * - наше: бонусы характеристик, скорость, навык, который раса даёт сама,
 *   особенности «Неподвижный взгляд» и «Холодный расчёт», вся проза, возраст,
 *   мировоззрение и рост.
 *
 * ПОЧЕМУ У РАСЫ НЕТ ВРОЖДЁННОГО КОЛДОВСТВА, хотя у наших же существ оно есть.
 * Это сознательная разница, а не недосмотр. У чужой играбельной расы той же
 * ниши врождённые заклинания — главная и самая узнаваемая часть пакета, и
 * повторить её значило бы воспроизвести чужую расу пакетом, чего карточка
 * прямо запрещает. Наш серпент разменивает колдовство на холодную выдержку:
 * Телосложение вместо Харизмы, «Холодный расчёт» вместо заклинаний. Цена
 * размена названа игроку в тексте расы.
 *
 * Отсюда же следствие: заклинаний раса не даёт ни одного, поэтому ни
 * `spells.json`, ни заговоров расы она не касается и второго владельца
 * заклинания не появляется. Скорость объявлена БАЗОЙ (`RACE_SPEED_FEET`), а не
 * слоем к `effectiveStats.ts`.
 */

