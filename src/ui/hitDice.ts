/**
 * Кости Хитов: сколько осталось, трата и возврат.
 *
 * ЕДИНСТВЕННЫЙ ВЛАДЕЛЕЦ предела «осталось не ниже нуля и не выше уровня» —
 * ровно тем же правилом, что `spellSlots.ts` владеет пределом ячеек. Путей
 * записи больше одного: короткий отдых тратит кость по одной, длинный отдых
 * возвращает половину максимума, а дальше сюда придут «Песнь отдыха» барда и
 * строка гриба «Коричневый Колпак», которые сегодня описательные ровно потому,
 * что тратить было нечего. Свой `Math.min`/`Math.max` у кнопки — это второй
 * владелец предела, и он запрещён.
 *
 * Максимум здесь не хранится и не приходит параметром отдельно от уровня: по
 * SRD Костей Хитов ровно столько, каков уровень персонажа, — тем же правилом,
 * которым максимум ресурса принадлежит таблице прогрессии, а не сохранению.
 * Поэтому левел-ап поднимает запас сам, а потраченные кости обратно не даёт.
 *
 * Персонаж хранит ПОТРАЧЕНО (`Character.hitDiceSpent`), а не ОСТАЛОСЬ: у
 * сохранения, записанного до появления поля, оно приходит нулём, и ноль обязан
 * значить «запас полон». У ресурсов ту же беду обходит `resourceCurrent`
 * («нет записи» отличимо от нуля, потому что запись — элемент массива), а у
 * простого числа так нельзя.
 */

/** Максимум Костей Хитов — это и есть уровень; нецелое и отрицательное уровнем не считается. */
function poolSize(level: number): number {
  return Number.isFinite(level) ? Math.max(0, Math.floor(level)) : 0;
}

/**
 * Потрачено, приведённое к пределу: ниже нуля и выше запаса «потрачено» не
 * бывает. Данные старого сохранения и уровень, упавший ниже потраченного,
 * считаются пустым запасом, а не отрицательным остатком.
 */
function clampSpent(spent: number, level: number): number {
  const cap = poolSize(level);
  if (!Number.isFinite(spent)) return 0;
  return Math.max(0, Math.min(cap, Math.floor(spent)));
}

/** Сколько Костей Хитов осталось: уровень минус потраченное. */
export function hitDiceLeft(spent: number, level: number): number {
  return poolSize(level) - clampSpent(spent, level);
}

/**
 * Трата одной кости — новое значение `hitDiceSpent`. Пустой запас возвращает
 * потраченное без изменений: выйти за уровень этим путём нельзя, а звук предела
 * и подпись — забота вызывающего, как у `spendResource` на листе.
 */
export function spendHitDie(spent: number, level: number): number {
  const current = clampSpent(spent, level);
  return hitDiceLeft(current, level) > 0 ? current + 1 : current;
}

/**
 * Возврат `count` костей — новое значение `hitDiceSpent`. Больше потраченного
 * не вернётся (потрачена одна из десяти — длинный отдых возвращает одну, а не
 * половину уровня), нечисловое и отрицательное `count` возвращают ноль костей —
 * ровно как `restoreSlots` обходится с таким же вводом.
 */
export function restoreHitDice(spent: number, level: number, count: number): number {
  const current = clampSpent(spent, level);
  const asked = Math.floor(count);
  const back = Math.min(Math.max(0, Number.isFinite(asked) ? asked : 0), current);
  return current - back;
}
