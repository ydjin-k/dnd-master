/** Строка таблицы уровней для статьи. Числа — те же владельцы, что кормят лист. */
function levelTableRow(level: number, features: string): string[] {
  const known = stepAt(INFUSIONS_KNOWN_STEPS, level);
  const infused = stepAt(INFUSED_ITEMS_STEPS, level);
  const slots = ARTIFICER_SLOTS[level];
  const cell = (n: number) => (n ? String(n) : "—");
  return [
    String(level),
    `+${2 + Math.floor((level - 1) / 4)}`,
    features,
    cell(known),
    cell(infused),
    String(stepAt(ARTIFICER_CANTRIPS_STEPS, level)),
    cell(slots[0]),
    cell(slots[1]),
    cell(slots[2]),
  ];
}

