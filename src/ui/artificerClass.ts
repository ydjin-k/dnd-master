/** Абзацы особенностей уровней 2-12 для статьи — из `ARTIFICER_LEVEL_FEATURES`, второй копии текста нет. */
function levelFeatureBlocks(): RuleBlock[] {
  return Object.entries(ARTIFICER_LEVEL_FEATURES).flatMap(([level, features]) =>
    features.flatMap((feature): RuleBlock[] => [
      { type: "heading", level: 2, text: feature.name },
      { type: "paragraph", text: `${level} уровень.` },
      { type: "paragraph", text: feature.description },
    ]),
  );
}
