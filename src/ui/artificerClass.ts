/** Абзацы одной специальности: «Имя (N уровень). Текст.» — из тех же данных, что архетип. */
function specialtyBlocks(spec: ClassSubclass): RuleBlock[] {
  const blocks: RuleBlock[] = [
    { type: "heading", level: 3, text: spec.name },
    { type: "paragraph", text: spec.description ?? "" },
  ];
  for (const [level, features] of Object.entries(spec.featuresByLevel)) {
    for (const feature of features) {
      blocks.push({ type: "paragraph", text: `${feature.name} (${level} уровень). ${feature.description}` });
    }
  }
  for (const option of spec.grants?.choices?.flatMap((choice) => choice.options) ?? []) {
    blocks.push({ type: "paragraph", text: `${option.label}. ${option.description}` });
  }
  blocks.push({
    type: "paragraph",
    text: `На 15 уровне — «${SPECIALTY_LEVEL_15[spec.name]}», выше нынешнего потолка приложения.`,
  });
  return blocks;
}

