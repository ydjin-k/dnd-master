/**
 * Последняя подошедшая ступень лесенки «с какого уровня → сколько всего»; 0 —
 * ниже первой ступени. То же правило, что `knownAt` у Алхимика и
 * `classChoiceKnownAt` общего механизма, но без импорта значения: этот файл
 * берёт оттуда только типы.
 */
export function stepAt(steps: readonly (readonly [number, number])[], level: number): number {
  let value = 0;
  for (const [from, count] of steps) {
    if (level >= from) value = count;
  }
  return value;
}

