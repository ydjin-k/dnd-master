/**
 * Одна из пяти рас пачки B — «Фирболг». Наша собственная, не SRD.
 *
 * ГДЕ ОНА ЖИВЁТ И ПОЧЕМУ ИМЕННО ЗДЕСЬ. Разобрано один раз и общо для всех наших
 * рас — `docs/design/own-races-how-to.md` и шапка `abyssElfRace.ts`. Коротко: в
 * `src-tauri/rules/rules.json` лежит ровно SRD 5.1, подвал вкладки «Правила»
 * обещает SRD за всё, что пришло оттуда, и раса, положенная в тот файл, молча
 * получила бы чужую подпись. Поэтому наша раса — отдельный модуль, а факт «это
 * наше» объявлен ровно в одном месте: `OWN_RULE_TOPICS` (`ownRuleTopics.ts`).
 *
 * ОТКУДА ВЗЯТО ИМЯ. Решение владельца 27.09.2026: имена десяти новых рас берутся
 * из его файлов («их брать можно, это информация в свободном доступе»), а
 * содержание пишется своё. Имя прогнано по сторожу
 * `own_creatures_never_use_product_identity_names` (`combat.rs`) — ни под одну
 * из 36 основ `FORBIDDEN_STEMS` и ни под одно из 9 слов `FORBIDDEN_WORDS` оно не
 * попадает.
 *
 * ЧТО ВЗЯТО ИЗ SRD, А ЧТО НАШЕ. Границу видно построчно:
 * - из открытого бестиария (`src-tauri/bestiary/bestiary.json`, подпись
 *   CC BY 4.0) взято три факта. Первый — **язык великанов**: на нём говорят
 *   открытые стат-блоки `hill-giant`, `stone-giant`, `cloud-giant` и соседи, и
 *   лесной великан берёт его оттуда. Второй — **язык Сильван**: на нём говорят
 *   открытые феи `dryad`, `treant`, `satyr` и `sprite`, и фейская родня нашей
 *   расы берёт его там же. Третий — **формулировка неподвижности**: «Ложная
 *   внешность. Пока древень остаётся неподвижным, он неотличим от обычного
 *   дерева.» стоит в стат-блоках `treant` и `awakened-tree`, и наше «Стоять
 *   деревом» повторяет её, а не заводит вторую формулировку того же правила;
 * - наше: бонусы характеристик, скорость, размер, навык, который раса даёт
 *   сама, три особенности ниже («Стоять деревом» как правило расы, «Шаг по
 *   бурелому», «Слово без оружия»), вся проза, все четыре таблицы, возраст,
 *   мировоззрение и рост.
 *
 * Играбельный фирболг из чужой книги как пакет здесь не воспроизводится.
 * Оттуда не взято НИ ОДНОГО числа и ни одной черты: у чужой расы бонусы стоят
 * на Мудрости и Силе, рост от 7 до 8 футов, два заклинания раздаются
 * особенностью с перезарядкой на отдыхе, бонусным действием включается
 * невидимость, грузоподъёмность считается на категорию размера выше, а
 * общение со зверями и растениями даёт преимущество на проверки Харизмы.
 * Здесь бонус на Телосложении вместо Силы, рост ниже, заклинаний нет вовсе,
 * невидимости нет, грузоподъёмность не тронута, и ни одна черта не говорит ни
 * про зверей, ни про растения.
 *
 * ПОЧЕМУ БОНУСЫ РАЗОШЛИСЬ И С ЧУЖОЙ РАСОЙ, И С НАШИМ ГОЛИАФОМ. Мудрость + Сила
 * — набор чужого пакета; Сила + Мудрость — уже занятый набор нашего Голиафа
 * (`goliathRace.ts`). Фирболг получает Мудрость + Телосложение: лесом он живёт
 * наблюдением и зимовкой, а не силовой работой, и это единственная расходящаяся
 * с обоими пара, которая отвечает нише.
 *
 * ЧЕГО У ЭТОЙ РАСЫ НЕТ И ПОЧЕМУ. Заклинаний она не даёт ни одного — и это не
 * упущение: раздатчики заговоров и расовых ячеек сегодня умеют ровно одну расу
 * (Эльфа бездны), обобщать их — отдельная карточка, а дописать ветку в
 * `abyssElfRace.ts` значило бы сделать файл Эльфа бездны владельцем чужих
 * фактов. Поэтому ниша закрыта особенностями, как у всех пяти рас пачки A.
 * Тёмного зрения у неё нет: открытые феи его не дают поголовно (`treant`,
 * `satyr` и `sprite` — без чувств вовсе, тёмное зрение есть только у `dryad`),
 * и приписать его «как соседям» значило бы выдумать число. Сопротивления магии
 * у неё тоже нет, хотя открытые феи его дают: эту формулировку в наших расах
 * уже держат Сатир и Серпенты, и третья копия сделала бы её общей приметой
 * вместо приметы расы. Прибавки к хитам у неё нет. Скорость она объявляет базой
 * (`RACE_SPEED_FEET`), а не слоем к `effectiveStats.ts`.
 */

