//! Журнал транзакций (§34–§35): `EngineState.history`.
//!
//! Он не для игрока, а для движка — им будет откатываться действие. Откат в
//! этой карточке не делается сознательно (сначала должно накопиться, что
//! откатывать), но транзакции пишутся с первого дня, иначе первая же версия с
//! Undo окажется без истории у уже сыгранных кампаний.
//!
//! Показывать его игроку нельзя: это не лог приключения. Три журнала и их
//! владельцы разведены в §29.2 (правка 23.09.2026) — дневник кампании пишет
//! только игрок, лог приключения только движок, журнал транзакций только
//! `mutate::apply`.

use super::mutate::{Transaction, WritePermit};
use super::state::EngineState;

/// Номер следующей транзакции — сплошная нумерация с единицы.
///
/// Считается от длины журнала, а не хранится отдельным счётчиком: счётчик стал
/// бы вторым владельцем ответа «сколько их было» и разошёлся бы с журналом при
/// первом же откате.
pub fn next_id(state: &EngineState) -> u64 {
    state.history().len() as u64 + 1
}

/// Положить транзакцию в журнал. Разрешение на запись приходит из
/// `mutate::apply` — своего этот модуль не создаёт и создать не может.
pub fn append(state: &mut EngineState, permit: &WritePermit, transaction: Transaction) {
    state.push_transaction(permit, transaction);
}
